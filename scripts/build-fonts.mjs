/* Emit the Japanese web fonts as a standalone, non-render-blocking stylesheet.
   Fontsource's sliced CSS is ~120 @font-face rules per weight; bundled into the
   main CSS it blocked first paint. Here we copy the woff2 slices to
   public/fonts/ and write public/fonts/fonts.css, which Base.astro loads
   asynchronously (text paints in the fallback first, font-display: swap).
   Output is generated — public/fonts/ is gitignored. */

import fs from 'node:fs'
import path from 'node:path'

// To swap fonts: install other @fontsource packages, list their CSS files here,
// and update --font-sans / --font-serif in src/styles/tokens.css.
const SOURCES = [
  'node_modules/@fontsource/zen-kaku-gothic-new/400.css',
  'node_modules/@fontsource/zen-kaku-gothic-new/700.css',
  'node_modules/@fontsource/shippori-mincho-b1/700.css',
]
const OUT_DIR = 'public/fonts'

fs.rmSync(OUT_DIR, { recursive: true, force: true })
fs.mkdirSync(OUT_DIR, { recursive: true })

let css = '/* generated by scripts/build-fonts.mjs — do not edit */\n'
let copied = 0
for (const src of SOURCES) {
  const dir = path.dirname(src)
  const text = fs
    .readFileSync(src, 'utf8')
    // keep woff2 only; every browser we target supports it
    .replace(/,\s*url\([^)]+\.woff\) format\('woff'\)/g, '')
    .replace(/url\(\.\/files\/([^)]+\.woff2)\)/g, (_, file) => {
      fs.copyFileSync(path.join(dir, 'files', file), path.join(OUT_DIR, file))
      copied++
      return `url(/fonts/${file})`
    })
    .replace(/\/\*[^*]*\*\/\n/g, '')
    .replace(/font-display: swap;/g, `font-display: ${process.env.FONT_DISPLAY || 'swap'};`)
  css += text
}
fs.writeFileSync(path.join(OUT_DIR, 'fonts.css'), css)
console.log(`[fonts] ${copied} woff2 files, fonts.css ${(css.length / 1024).toFixed(0)} KiB`)
